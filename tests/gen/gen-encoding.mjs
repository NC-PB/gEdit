// Writes the byte-exact encoding fixtures in tests/fixtures/nc/encoding/.
//
// These files hold bytes that editors and git like to "fix" (BOMs, CR-only breaks,
// NUL runs, Windows-1252, UTF-16), so they are built here instead of by hand. The
// output is deterministic; tests/unit/fixtures.test.ts checks that the committed
// files still equal it.
//
// Usage: node tests/gen/gen-encoding.mjs [--check]
//   --check  compare only; exit 1 if a file is missing, different or unexpected

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ENCODING_DIR = fileURLToPath(new URL('../fixtures/nc/encoding/', import.meta.url));

const CRLF = '\r\n';

/**
 * A short milling program. `title` goes into the provenance comment, `extra` are
 * comment lines inserted after the program number (used for non-ASCII text).
 * @param {string} title
 * @param {string[]} [extra]
 * @returns {string[]}
 */
function programLines(title, extra = []) {
  return [
    `(WRITTEN FOR GEDIT - GENERATED BY TESTS/GEN/GEN-ENCODING.MJS: ${title})`,
    '%',
    'O2001 (ENCODING)',
    ...extra,
    'G21 G17 G40 G49 G80 G90 G94',
    'T1 M6',
    'S3000 M3',
    'G0 X0. Y0.',
    'G43 Z25. H1 M8',
    'G1 Z-1. F200.',
    'X40. F800.',
    'G0 Z25.',
    'M30',
    '%',
  ];
}

/**
 * Joins lines with `eol`, including a break after the last line.
 * @param {string[]} lines
 * @param {string} eol
 */
function withEol(lines, eol) {
  return lines.map((line) => line + eol).join('');
}

/** @param {string} text */
function ascii(text) {
  const bytes = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code > 0x7f) throw new Error(`not ASCII: ${text[i]}`);
    bytes[i] = code;
  }
  return bytes;
}

/** @param {string} text */
function utf8(text) {
  return new TextEncoder().encode(text);
}

// The few non-ASCII characters the Windows-1252 fixture uses, with their bytes.
/** @type {Record<string, number>} */
const CP1252 = { '€': 0x80, '–': 0x96, '°': 0xb0, 'µ': 0xb5, 'Ø': 0xd8, 'Ü': 0xdc };

/** @param {string} text */
function cp1252(text) {
  const bytes = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    const byte = code < 0x80 ? code : CP1252[text[i]];
    if (byte === undefined) throw new Error(`no Windows-1252 byte for ${text[i]}`);
    bytes[i] = byte;
  }
  return bytes;
}

/**
 * UTF-16 with a byte order mark. JS strings are UTF-16 already, so each code unit
 * becomes two bytes.
 * @param {string} text
 * @param {boolean} littleEndian
 */
function utf16(text, littleEndian) {
  const bytes = new Uint8Array(2 + text.length * 2);
  const view = new DataView(bytes.buffer);
  view.setUint16(0, 0xfeff, littleEndian);
  for (let i = 0; i < text.length; i++) view.setUint16(2 + i * 2, text.charCodeAt(i), littleEndian);
  return bytes;
}

/** @param {...Uint8Array} parts */
function concat(...parts) {
  const bytes = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let offset = 0;
  for (const part of parts) {
    bytes.set(part, offset);
    offset += part.length;
  }
  return bytes;
}

/**
 * Bytes that look like binary data: about half of them NUL, the rest from a fixed
 * linear congruential sequence (never 0), ending in a non-NUL byte so no trailer
 * is trimmed.
 * @param {number} length
 */
function binaryNoise(length) {
  const bytes = new Uint8Array(length);
  let state = 12345;
  for (let i = 0; i < length; i++) {
    state = (Math.imul(state, 1103515245) + 12345) >>> 0;
    bytes[i] = i % 2 === 0 ? 0 : 1 + ((state >>> 16) % 255);
  }
  bytes[length - 1] = 0xff;
  return bytes;
}

/**
 * Every encoding fixture, by file name, in a fixed order.
 * @returns {Map<string, Uint8Array>}
 */
export function buildEncodingFixtures() {
  /** @type {Map<string, Uint8Array>} */
  const files = new Map();

  files.set(
    'utf8-lf.nc',
    utf8(
      withEol(
        programLines('UTF-8, LF', [
          '(Ø10 END MILL, 30° CHAMFER, RA 0.8 µM)',
          '(CUSTOMER: MÜLLER AG, ROUGH → FINISH)',
        ]),
        '\n',
      ),
    ),
  );

  files.set(
    'utf8-bom-crlf.nc',
    concat(
      new Uint8Array([0xef, 0xbb, 0xbf]),
      utf8(withEol(programLines('UTF-8 WITH BOM, CRLF', ['(Ø10 END MILL, 30° CHAMFER)']), CRLF)),
    ),
  );

  // Ø followed by an ASCII digit is not valid UTF-8, so the file decodes as Windows-1252.
  files.set(
    'cp1252-crlf.nc',
    cp1252(
      withEol(
        programLines('WINDOWS-1252, CRLF', [
          '(Ø10 END MILL, 30° CHAMFER, RA 0.8 µM)',
          '(CUSTOMER: MÜLLER AG – TOOL COST 12 €)',
        ]),
        CRLF,
      ),
    ),
  );

  files.set('cr-only.nc', ascii(withEol(programLines('ASCII, CR ONLY'), '\r')));

  // 10 CRLF, 2 LF and 1 CR: CRLF is the clear majority.
  const mixed = programLines('ASCII, MIXED LINE ENDINGS');
  const mixedEol = mixed.map((_, i) => (i === 5 || i === 9 ? '\n' : i === 7 ? '\r' : CRLF));
  files.set('mixed-eol.nc', ascii(mixed.map((line, i) => line + mixedEol[i]).join('')));

  // Punched-tape leader and trailer: NUL runs around the program.
  const nuls = new Uint8Array(40);
  files.set(
    'nul-leader-trailer.nc',
    concat(nuls, ascii(withEol(programLines('ASCII, CRLF, 40 NUL LEADER AND TRAILER'), CRLF)), nuls),
  );

  // Three stray NULs inside the text (a transmission glitch), far below 10 %.
  const inside = programLines('ASCII, CRLF, 3 NUL BYTES INSIDE').map((line) =>
    line === 'G0 X0. Y0.' ? 'G0 X0.\0 Y0.' : line === 'X40. F800.' ? 'X40.\0\0 F800.' : line,
  );
  files.set('nul-inside.nc', ascii(withEol(inside, CRLF)));

  // Mostly NUL: refused as binary.
  files.set(
    'nul-heavy.bin',
    concat(ascii('(WRITTEN FOR GEDIT - GENERATED BY TESTS/GEN/GEN-ENCODING.MJS: BINARY DATA)' + CRLF), binaryNoise(512)),
  );

  const wide = withEol(programLines('UTF-16, CRLF', ['(Ø10 END MILL, 30° CHAMFER, ROUGH → FINISH)']), CRLF);
  files.set('utf16le-bom.nc', utf16(wide, true));
  files.set('utf16be-bom.nc', utf16(wide, false));

  return files;
}

/** @param {boolean} check */
function main(check) {
  const files = buildEncodingFixtures();
  /** @type {string[]} */
  const problems = [];
  if (!check) mkdirSync(ENCODING_DIR, { recursive: true });

  for (const [name, bytes] of files) {
    const path = join(ENCODING_DIR, name);
    if (check) {
      let current;
      try {
        current = readFileSync(path);
      } catch {
        problems.push(`missing: ${name}`);
        continue;
      }
      if (!current.equals(bytes)) problems.push(`differs: ${name}`);
    } else {
      writeFileSync(path, bytes);
    }
  }

  let present = /** @type {string[]} */ ([]);
  try {
    present = readdirSync(ENCODING_DIR);
  } catch {
    // missing folder: every file is already reported as missing
  }
  for (const name of present) if (!files.has(name)) problems.push(`not generated: ${name}`);

  if (problems.length > 0) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log(`${check ? 'checked' : 'wrote'} ${files.size} files in ${ENCODING_DIR}`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main(process.argv.includes('--check'));
}
